#!/usr/bin/env python3
"""Generate the files derived from docs/cmux.schema.json.

- the schema embedded in CmuxFoundation for the native validator
- the cmux-settings skill's key reference (references/all-keys.md)

Run with --check to fail when either output is stale.
"""

from __future__ import annotations

import argparse
import base64
import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "docs" / "cmux.schema.json"
EMBEDDED = (
    ROOT
    / "Packages"
    / "macOS"
    / "CmuxFoundation"
    / "Sources"
    / "CmuxFoundation"
    / "ConfigValidation"
    / "CmuxConfigSchema.generated.swift"
)
ALL_KEYS = ROOT / "skills" / "cmux-settings" / "references" / "all-keys.md"

# Sections parsed by CmuxConfig (actions, commands, layouts) rather than the
# settings file store; the key reference lists settings only.
STRUCTURAL_SECTIONS = {
    "$schema",
    "schemaVersion",
    "actions",
    "ui",
    "commands",
    "vault",
    "newWorkspaceCommand",
    "surfaceTabBarButtons",
    "agentChat",
}


def embedded_source() -> str:
    encoded = base64.b64encode(SCHEMA.read_bytes()).decode("ascii")
    chunks = [encoded[i : i + 400] for i in range(0, len(encoded), 400)]
    body = "\n".join(f'        "{chunk}",' for chunk in chunks)
    return f"""// Generated by scripts/generate-cmux-config-schema.py. Do not edit.
// Source: docs/cmux.schema.json

import Foundation

enum CmuxEmbeddedConfigSchema {{
    static let data: Data = {{
        let base64 = [
{body}
        ].joined()
        guard let data = Data(base64Encoded: base64) else {{
            preconditionFailure("embedded cmux.json schema is corrupt")
        }}
        return data
    }}()
}}
"""


def type_text(node: dict[str, Any]) -> str:
    choices = node.get("enum") or next(
        (alt["enum"] for alt in node.get("anyOf", []) if "enum" in alt), None
    )
    if choices:
        return " or ".join(f"`{json.dumps(choice)}`" for choice in choices)
    ref = node.get("$ref", "")
    if ref.endswith("/colorHexOrNull"):
        return "hex color or null"
    if ref.endswith("/colorHex"):
        return "hex color"
    kind = node.get("type")
    if isinstance(kind, list):
        return " or ".join(kind)
    if kind:
        return kind
    alternatives = [alt.get("type") for alt in node.get("oneOf", []) + node.get("anyOf", [])]
    return " or ".join(t for t in alternatives if isinstance(t, str)) or "value"


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def key_rows(path: str, node: dict[str, Any], skip: set[str]) -> list[str]:
    properties = {k: v for k, v in node.get("properties", {}).items() if k not in skip}
    if properties:
        return [row for key, child in properties.items() for row in key_rows(f"{path}.{key}", child, skip)]
    default = f"`{json.dumps(node['default'], ensure_ascii=False)}`" if "default" in node else ""
    return [f"| `{path}` | {type_text(node)} | {default} | {cell(node.get('description', ''))} |"]


def all_keys_markdown() -> str:
    schema = json.loads(SCHEMA.read_text())
    action_ids = set(schema["$defs"]["shortcutActionId"]["enum"])
    lines = [
        "# All settings keys",
        "",
        "Generated by `scripts/generate-cmux-config-schema.py` from `docs/cmux.schema.json`. "
        "Shortcut action ids are listed in [shortcut-actions.md](shortcut-actions.md).",
    ]
    for section, node in schema["properties"].items():
        if section in STRUCTURAL_SECTIONS:
            continue
        rows = key_rows(section, node, action_ids | ({"byCwd"} if section == "workspaceGroups" else set()))
        lines += ["", f"## {section}", ""]
        if node.get("properties") and node.get("description"):
            lines += [node["description"], ""]
        lines += ["| Key | Type | Default | Description |", "|---|---|---|---|", *rows]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    outputs = {EMBEDDED: embedded_source(), ALL_KEYS: all_keys_markdown()}
    if args.check:
        stale = [path for path, text in outputs.items() if not path.exists() or path.read_text() != text]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is stale; run {Path(__file__).name}")
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
